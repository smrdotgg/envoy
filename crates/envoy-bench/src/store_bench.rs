//! Search and open, timed on the engine's own code path: the same `Store` calls, arguments and
//! connection setup the engine thread makes for `Command::List` and `Command::Open`.
//!
//! - Search: `Query::parse` + `Store::list_paged(view, query, conversations = true, limit =
//!   3000, me, engine::FIRST_PAGE)`, exactly what one keystroke in the search field costs
//!   (search runs as you type), timed to the rows the user sees: the engine sends the first
//!   page of a long list (the top `FIRST_PAGE` rows, final) as soon as it's read and the rest
//!   after it (law 1 of docs/NORTH_STAR.md: what can't meet the budget streams in), so that's
//!   the first page's time, or the whole list's when it's short. The whole list's time is
//!   printed beside it. Each query runs once cold (first time in this process) and then
//!   `REPEAT` more times; the gate is the median of those 21 runs, with the p90, the cold run
//!   and the worst printed beside it. Every prefix typed on the way to two queries runs 5 times;
//!   the gate is the worst keystroke's median.
//! - Split inbox tabs: what the engine does for `Command::List` with a category: the tab's rows
//!   (`list_paged` with the category), timed to the first page like search and gated like it
//!   (median of 21), then every tab's unread count (`Store::category_counts`), which the whole
//!   list's time includes. Switching tabs round and round is timed too (the worst switch's
//!   median), beside the unsplit inbox.
//! - Open: `Store::thread(id, conversations = true)`: reads the conversation, its bodies,
//!   converts HTML to Markdown on first open (and writes it back, as the engine does), and
//!   parses the HTML into the layout tree the reader draws. Each sample is a different message,
//!   so "first open" is really first; the gate is the p95 of the samples (the 3rd worst of 40).
//!
//! - Recipient suggestions: `Store::suggest(typed, me, now, engine::SUGGESTIONS)`, what one
//!   keystroke in a To field costs (the composer asks on every one, off the UI thread), for every
//!   prefix typed on the way to two names and an address, `TYPED_RUNS` times each; gated like
//!   search typing (the worst keystroke's median), at the search budget: it's a local search.
//!   A mailbox generated by a build from before contacts were kept has them counted first
//!   (`Store::backfill_contacts`, as the engine does in the background), timed. Then the same on
//!   a cache of `STRESS_PEOPLE` different people, far more than anyone writes to (not gated).
//!
//! Why search gates on the median: on the macOS runner (a VM) runs stall for up to 2 s, sometimes
//! several within one query's 21 runs (Archive "meeting": p50 151 ms, p90 287 ms, worst 2032
//! ms; another query with a 53 ms median measured 1423 ms once). The worst or even the p90 then
//! measures the hypervisor and fails passing checks at random; the median measures the code and
//! still moves when the code gets slower. Open samples are each one distinct first open, taking
//! well under a millisecond, so a stall hits at most one of them: the p95 (3rd worst of 40)
//! ignores it.

use std::collections::HashSet;
use std::path::Path;
use std::time::Instant;

use anyhow::Result;
use envoy_core::engine::FIRST_PAGE;
use envoy_core::model::{Category, Role, View};
use envoy_core::store::{Query, Store};

use crate::mailbox::{ACCOUNT, END, FIRST, LAST, ME};
use crate::report::{Check, budget, p50_max, quantile};

const REPEAT: usize = 20;
const TYPED_RUNS: usize = 5;
const LIMIT: u32 = 3000; // what `App::request_list` asks for

fn inbox() -> View {
    View::Role { account: None, role: Role::Inbox }
}

fn archive() -> View {
    View::Role { account: None, role: Role::Archive }
}

/// What people type, finished: a common word (in ~25% of mail), a medium one (a few percent), a rare
/// one, two words, the filters, a miss. Inbox is the default view; Archive is the big folder.
const QUERIES: &[(&str, &str)] = &[
    ("inbox", "meeting"),
    ("inbox", "invoice"),
    ("inbox", "budget review"),
    ("inbox", "pancakes"),
    ("inbox", "from:alice"),
    ("inbox", "from:northwind"),
    ("inbox", "to:maya"),
    ("inbox", "subject:lunch"),
    ("inbox", "is:unread"),
    ("inbox", "is:starred"),
    ("inbox", "has:attachment"),
    ("inbox", "from:sam is:unread"),
    ("inbox", "qwxzv"),
    ("archive", "meeting"),
    ("archive", "invoice"),
    ("archive", "from:alice"),
    ("archive", "is:unread"),
];

/// Search runs on every keystroke, so the prefixes on the way to a query are searches too.
const TYPED: &[(&str, &str)] = &[("inbox", "invoice"), ("inbox", "from:alice")];

fn view_of(name: &str) -> View {
    if name == "archive" { archive() } else { inbox() }
}

/// One keystroke: (ms to the rows shown first, ms to the whole list, rows in the whole list).
fn timed(st: &Store, view: &View, q: &str, me: &HashSet<String>) -> Result<(f64, f64, usize)> {
    let t = Instant::now();
    let query = Query::parse(q);
    let mut first = None;
    let rows = st.list_paged(view, &query, true, LIMIT, me, FIRST_PAGE, &mut |_| {
        first.get_or_insert(t.elapsed());
    })?;
    let whole = t.elapsed();
    let ms = |d: std::time::Duration| d.as_secs_f64() * 1000.0;
    Ok((ms(first.unwrap_or(whole)), ms(whole), rows.len()))
}

fn time_query(st: &Store, view: &View, q: &str, me: &HashSet<String>) -> Result<(f64, usize)> {
    let (shown, _, n) = timed(st, view, q, me)?;
    Ok((shown, n))
}

pub fn run(home: &Path, checks: &mut Vec<Check>, search: bool, open: bool) -> Result<()> {
    let db = home.join("mail.sqlite");
    anyhow::ensure!(db.exists(), "no mailbox at {} (run `envoy-bench gen` first)", db.display());
    let me: HashSet<String> = [ME.to_string()].into();

    // Startup's data path, for the breakdown: open the cache and read the first screen.
    let t = Instant::now();
    let st = Store::open(&db)?;
    let opened = t.elapsed().as_secs_f64() * 1000.0;
    let (first_list, first_whole, rows) = timed(&st, &inbox(), "", &me)?;
    let total: i64 = rusqlite::Connection::open(&db)?.query_row("SELECT COUNT(*) FROM messages", [], |r| r.get(0))?;
    checks.push(Check::info("store", "open cache", opened, "ms", format!("{total} messages in {}", human_size(std::fs::metadata(&db)?.len()))));
    checks.push(Check::info("store", "first inbox list", first_list, "ms", format!("startup's query, first run in this process: its first {FIRST_PAGE} rows; all {rows} in {first_whole:.1} ms")));

    if search {
        run_search(&st, &me, checks)?;
        run_contacts(home, &st, &me, checks)?;
        run_tabs(&st, &me, checks)?;
    }
    if open {
        run_open(&db, &st, checks)?;
    }
    Ok(())
}

fn run_search(st: &Store, me: &HashSet<String>, checks: &mut Vec<Check>) -> Result<()> {
    let mut all = Vec::new();
    let mut lines = Vec::new();
    let mut worst_whole = 0.0f64;
    for (v, q) in QUERIES {
        let view = view_of(v);
        let (cold, cold_whole, n) = timed(st, &view, q, me)?;
        let (mut runs, mut wholes) = (vec![cold], vec![cold_whole]);
        for _ in 0..REPEAT {
            let (shown, whole, _) = timed(st, &view, q, me)?;
            runs.push(shown);
            wholes.push(whole);
        }
        let (p50, max) = p50_max(&runs);
        let p90 = quantile(&runs, 0.9);
        let whole50 = p50_max(&wholes).0;
        worst_whole = worst_whole.max(whole50);
        lines.push(format!("  {v:>7}  {q:<22} {n:>5} rows  cold {cold:7.2} ms  p50 {p50:7.2} ms  p90 {p90:7.2} ms  max {max:7.2} ms  (whole list p50 {whole50:7.2} ms)"));
        all.extend(runs);
        checks.push(Check::gated(
            "search",
            format!("{v}: {q}"),
            p50,
            "ms",
            budget::SEARCH_MS,
            1.0,
            format!("median of {} (p90 {p90:.2}, cold {cold:.2}, max {max:.2}); {n} rows, the whole list in {whole50:.2}", REPEAT + 1),
        ));
    }
    let mut typed_all = Vec::new();
    for (v, q) in TYPED {
        let view = view_of(v);
        let mut worst = (0.0f64, String::new(), 0.0f64);
        for end in 1..=q.chars().count() {
            let prefix: String = q.chars().take(end).collect();
            let mut runs = Vec::new();
            let mut n = 0;
            for _ in 0..TYPED_RUNS {
                let (ms, rows) = time_query(st, &view, &prefix, me)?;
                runs.push(ms);
                n = rows;
            }
            let (median, max) = p50_max(&runs);
            typed_all.extend(runs.iter().copied());
            lines.push(format!("  {v:>7}  {:<22} {n:>5} rows  cold {:7.2} ms  p50 {median:7.2} ms  max {max:7.2} ms   (typing)", format!("{prefix:?}"), runs[0]));
            if median > worst.0 {
                worst = (median, prefix, max);
            }
        }
        checks.push(Check::gated(
            "search",
            format!("{v}: typing {q:?}"),
            worst.0,
            "ms",
            budget::SEARCH_MS,
            1.0,
            format!("worst keystroke {:?} of {} (median of {TYPED_RUNS}, max {:.2})", worst.1, q.chars().count(), worst.2),
        ));
    }
    println!("\nsearch (Store::list_paged, conversations, limit {LIMIT}, first page {FIRST_PAGE}; timed to the rows shown first):");
    for l in &lines {
        println!("{l}");
    }
    all.extend(typed_all);
    let (p50, max) = p50_max(&all);
    checks.push(Check::info("search", "all queries", max, "ms", format!("the single worst of {} runs (p50 {p50:.2} ms); each query gates on its own", all.len())));
    checks.push(Check::info(
        "search",
        "  whole lists",
        worst_whole,
        "ms",
        format!("the slowest query's median to its whole list (up to {LIMIT} rows); the first {FIRST_PAGE} show before it"),
    ));
    Ok(())
}

/// What's typed into a To field on the way to someone: two names (one with an accent) and an address.
const TYPED_CONTACTS: &[&str] = &["sofia garcía", "marcus", "alice.chen@n"];
/// The stress cache's people, each different.
const STRESS_PEOPLE: usize = 50_000;

fn run_contacts(home: &Path, st: &Store, me: &HashSet<String>, checks: &mut Vec<Check>) -> Result<()> {
    let t = Instant::now();
    let mut chunks = 0;
    while st.backfill_contacts(envoy_core::engine::CONTACTS_CHUNK)? {
        chunks += 1;
    }
    if chunks > 0 {
        let ms = t.elapsed().as_secs_f64() * 1000.0;
        let chunk = envoy_core::engine::CONTACTS_CHUNK;
        checks.push(Check::info("search", "recipients: counting an old cache's people", ms, "ms", format!("{chunks} chunks of {chunk} messages ({:.1} ms each), in the background: the writer is free between them", ms / chunks as f64)));
    }
    let people: i64 = rusqlite::Connection::open(home.join("mail.sqlite"))?.query_row("SELECT COUNT(DISTINCT email) FROM contacts", [], |r| r.get(0))?;
    let mut lines = Vec::new();
    time_contacts(st, me, &format!("{people} people"), &mut lines, checks, true)?;

    // A cache of far more people than anyone writes to.
    let db = home.join("contacts-stress.sqlite");
    let _ = std::fs::remove_file(&db);
    let stress = Store::open(&db)?;
    stress.set_me(me.clone());
    stress.upsert_mailbox(ACCOUNT, "INBOX", "Inbox", Role::Inbox, "/", true)?;
    let t = Instant::now();
    stress.transaction(|s| {
        for i in 0..STRESS_PEOPLE {
            let (f, l) = (FIRST[i % FIRST.len()], LAST[(i / FIRST.len()) % LAST.len()]);
            let local: String = format!("{f}.{l}{i}").to_lowercase().chars().filter(|c| c.is_ascii_alphanumeric() || *c == '.').collect();
            let raw = format!("From: {f} {l} <{local}@x{}.example>\r\nTo: {ME}\r\nSubject: hi\r\nMessage-ID: <s{i}@stress>\r\nDate: {}\r\n\r\n", i % 97, chrono::DateTime::from_timestamp(END - i as i64 * 600, 0).map(|d| d.to_rfc2822()).unwrap_or_default());
            let p = envoy_core::mime::parse(raw.as_bytes(), true).ok_or_else(|| anyhow::anyhow!("stress message didn't parse"))?;
            s.upsert_header(ACCOUNT, "INBOX", i as u32 + 1, 0, raw.len() as u32, 0, &p)?;
        }
        Ok(())
    })?;
    let built = t.elapsed().as_secs_f64() * 1000.0;
    time_contacts(&stress, me, &format!("{STRESS_PEOPLE} people (stress, built in {built:.0} ms)"), &mut lines, checks, false)?;
    drop(stress);
    for ext in ["", "-wal", "-shm"] {
        let _ = std::fs::remove_file(home.join(format!("contacts-stress.sqlite{ext}")));
    }
    println!("\nrecipient suggestions (Store::suggest, {} at most; timed per keystroke):", envoy_core::engine::SUGGESTIONS);
    for l in &lines {
        println!("{l}");
    }
    Ok(())
}

/// Every prefix of [`TYPED_CONTACTS`] on `st`, `TYPED_RUNS` times each: a gated check per name
/// (the worst keystroke's median) when `gate`, else one line of information for them all.
fn time_contacts(st: &Store, me: &HashSet<String>, what: &str, lines: &mut Vec<String>, checks: &mut Vec<Check>, gate: bool) -> Result<()> {
    let mut all_worst = (0.0f64, String::new());
    for typed in TYPED_CONTACTS {
        let mut worst = (0.0f64, String::new(), 0.0f64);
        for end in 1..=typed.chars().count() {
            let prefix: String = typed.chars().take(end).collect();
            let mut runs = Vec::new();
            let mut n = 0;
            for _ in 0..TYPED_RUNS {
                let t = Instant::now();
                n = st.suggest(&prefix, me, END, envoy_core::engine::SUGGESTIONS)?.len();
                runs.push(t.elapsed().as_secs_f64() * 1000.0);
            }
            let (median, max) = p50_max(&runs);
            lines.push(format!("  {what:<24.24} {:<16} {n:>3} people  cold {:7.3} ms  p50 {median:7.3} ms  max {max:7.3} ms", format!("{prefix:?}"), runs[0]));
            if median > worst.0 {
                worst = (median, prefix, max);
            }
        }
        if worst.0 > all_worst.0 {
            all_worst = (worst.0, format!("{:?} typing {typed:?}", worst.1));
        }
        if gate {
            checks.push(Check::gated(
                "search",
                format!("recipients: typing {typed:?}"),
                worst.0,
                "ms",
                budget::SEARCH_MS,
                1.0,
                format!("worst keystroke {:?} of {} (median of {TYPED_RUNS}, max {:.3}); {what}", worst.1, typed.chars().count(), worst.2),
            ));
        }
    }
    if !gate {
        checks.push(Check::info("search", "recipients: a huge address book", all_worst.0, "ms", format!("worst keystroke {} (median of {TYPED_RUNS}); {what}", all_worst.1)));
    }
    Ok(())
}

/// A tab of the split inbox as the engine reads it: its rows, the first page sent ahead, then
/// the tabs' counts. (ms to the rows shown first, ms to the whole list and the counts, rows.)
fn timed_tab(st: &Store, view: &View, tab: Option<Category>, me: &HashSet<String>) -> Result<(f64, f64, usize)> {
    let t = Instant::now();
    let query = tab.map_or_else(Query::default, Query::in_category);
    let mut first = None;
    let rows = st.list_paged(view, &query, true, LIMIT, me, FIRST_PAGE, &mut |_| {
        first.get_or_insert(t.elapsed());
    })?;
    if tab.is_some() {
        st.category_counts(view, true)?;
    }
    let whole = t.elapsed();
    let ms = |d: std::time::Duration| d.as_secs_f64() * 1000.0;
    Ok((ms(first.unwrap_or(whole)), ms(whole), rows.len()))
}

fn run_tabs(st: &Store, me: &HashSet<String>, checks: &mut Vec<Check>) -> Result<()> {
    let view = inbox();
    let mut lines = Vec::new();
    let tabs: Vec<Option<Category>> = std::iter::once(None).chain(Category::ALL.into_iter().map(Some)).collect();
    for tab in &tabs {
        let name = tab.map_or("unsplit (today's list)", |c| c.label());
        let (cold, cold_whole, n) = timed_tab(st, &view, *tab, me)?;
        let (mut runs, mut wholes) = (vec![cold], vec![cold_whole]);
        for _ in 0..REPEAT {
            let (shown, whole, _) = timed_tab(st, &view, *tab, me)?;
            runs.push(shown);
            wholes.push(whole);
        }
        let (p50, max) = p50_max(&runs);
        let whole50 = p50_max(&wholes).0;
        lines.push(format!("  inbox  {name:<22} {n:>5} rows  cold {cold:7.2} ms  p50 {p50:7.2} ms  max {max:7.2} ms  (whole list p50 {whole50:7.2} ms)"));
        let detail = format!("median of {} (cold {cold:.2}, max {max:.2}); {n} conversations, the whole list in {whole50:.2}", REPEAT + 1);
        match tab {
            Some(c) => checks.push(Check::gated("search", format!("inbox tab: {}", c.label()), p50, "ms", budget::SEARCH_MS, 1.0, format!("{detail} (counts included)"))),
            None => checks.push(Check::info("search", "inbox, unsplit", p50, "ms", detail)),
        }
    }
    // Switching: each tab after the one before, round and round.
    let mut switches: Vec<Vec<f64>> = vec![Vec::new(); Category::ALL.len()];
    for _ in 0..TYPED_RUNS {
        for (i, c) in Category::ALL.into_iter().enumerate() {
            switches[i].push(timed_tab(st, &view, Some(c), me)?.0);
        }
    }
    let (worst, which) = switches.iter().enumerate().map(|(i, runs)| (p50_max(runs).0, Category::ALL[i])).fold((0.0f64, Category::Important), |a, b| if b.0 > a.0 { b } else { a });
    lines.push(format!("  inbox  switching tabs         worst switch (to {}) p50 {worst:7.2} ms over {TYPED_RUNS} rounds", which.label()));
    checks.push(Check::gated("search", "inbox: switching tabs", worst, "ms", budget::SEARCH_MS, 1.0, format!("the slowest switch's median (to {}) over {TYPED_RUNS} rounds of all four", which.label())));
    let t = Instant::now();
    for _ in 0..REPEAT {
        st.category_counts(&view, true)?;
    }
    let counts = t.elapsed().as_secs_f64() * 1000.0 / REPEAT as f64;
    checks.push(Check::info("search", "  tab counts", counts, "ms", "Store::category_counts for the inbox, mean"));
    println!("\nsplit inbox (list_paged with the category, conversations, limit {LIMIT}, first page {FIRST_PAGE}; then Store::category_counts):");
    for l in &lines {
        println!("{l}");
    }
    println!("  tab counts alone: {counts:.2} ms");
    Ok(())
}

fn run_open(db: &Path, st: &Store, checks: &mut Vec<Check>) -> Result<()> {
    let pick = rusqlite::Connection::open(db)?;
    let ids = |sql: &str| -> Result<Vec<i64>> {
        let mut stmt = pick.prepare(sql)?;
        let rows = stmt.query_map([ACCOUNT], |r| r.get(0))?;
        Ok(rows.collect::<rusqlite::Result<_>>()?)
    };
    let plain = ids(
        "SELECT m.id FROM messages m JOIN bodies b ON b.id = m.id WHERE m.account = ?1 AND m.mailbox = 'INBOX' AND b.html IS NULL
         AND (SELECT COUNT(*) FROM messages t WHERE t.account = m.account AND t.thread = m.thread) = 1 ORDER BY m.date DESC LIMIT 40",
    )?;
    let html = ids(
        "SELECT m.id FROM messages m JOIN bodies b ON b.id = m.id WHERE m.account = ?1 AND b.html IS NOT NULL AND b.markdown IS NULL
         AND length(b.html) > 8000 ORDER BY m.date DESC LIMIT 40",
    )?;
    let threads = ids(
        "SELECT MAX(m.id) FROM messages m WHERE m.account = ?1 GROUP BY m.thread HAVING COUNT(*) >= 6 ORDER BY MAX(m.date) DESC LIMIT 30",
    )?;
    let mut time_open = |name: &str, ids: &[i64], want: usize, what: &str| -> Result<()> {
        if ids.len() != want {
            checks.push(Check::invalid("open", name.to_string(), Some(budget::OPEN_MS), "ms", format!("found {} {what} to open, expected {want}: the mailbox isn't the one this harness generates", ids.len())));
            return Ok(());
        }
        let mut runs = Vec::new();
        let mut msgs = 0;
        for &id in ids {
            let t = Instant::now();
            let thread = st.thread(id, true)?;
            runs.push(t.elapsed().as_secs_f64() * 1000.0);
            anyhow::ensure!(thread.iter().all(|m| m.body.is_some()), "message {id} has no cached body");
            msgs += thread.len();
        }
        let (p50, max) = p50_max(&runs);
        let p95 = quantile(&runs, 0.95);
        println!("  open {name:<18} {:>3} samples  p50 {p50:7.2} ms  p95 {p95:7.2} ms  max {max:7.2} ms  ({:.1} messages each)", runs.len(), msgs as f64 / runs.len() as f64);
        checks.push(Check::gated("open", name.to_string(), p95, "ms", budget::OPEN_MS, 1.0, format!("p95 of {} {what} (p50 {p50:.2}, max {max:.2})", runs.len())));
        Ok(())
    };
    println!("\nopen (Store::thread, conversations):");
    time_open("plain text", &plain, 40, "single messages")?;
    time_open("HTML, first open", &html, 40, "newsletters (HTML → Markdown + layout tree)")?;
    time_open("HTML, reopen", &html, 40, "newsletters, Markdown cached")?;
    time_open("conversation ≥6", &threads, 30, "conversations, all bodies")?;
    Ok(())
}

pub fn human_size(bytes: u64) -> String {
    let mb = bytes as f64 / (1024.0 * 1024.0);
    if mb >= 1024.0 { format!("{:.2} GB", mb / 1024.0) } else { format!("{mb:.0} MB") }
}
